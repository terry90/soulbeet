"""Stands in for yt-dlp in the e2e stack: "downloads" a catalogue track as an Ogg Opus file of
silence as long as the track, and answers yt-dlp's own test download (the health probe) without
writing anything."""

import json
import os
import struct
from pathlib import Path

CATALOGUE = Path(__file__).resolve().parent.parent / "catalogue.json"
# Opus counts at 48 kHz, and a decoder skips this many samples first.
RATE, PRE_SKIP = 48_000, 312
# Each packet is a 20 ms CELT frame with no data: silence.
PACKET, SAMPLES_PER_PACKET = b"\xf8", 960


def crc32(data):
    """The CRC of an Ogg page: polynomial 0x04c11db7, not reflected."""
    crc = 0
    for byte in data:
        crc ^= byte << 24
        for _ in range(8):
            crc = ((crc << 1) ^ 0x04C11DB7) if crc & 0x80000000 else crc << 1
            crc &= 0xFFFFFFFF
    return crc


def page(kind, granule, sequence, packets):
    header = b"OggS" + bytes([0, kind]) + struct.pack("<qII", granule, 1, sequence) + bytes(4)
    body = bytes([len(packets)]) + bytes(len(p) for p in packets) + b"".join(packets)
    raw = header + body
    return raw[:22] + struct.pack("<I", crc32(raw)) + raw[26:]


def silence(seconds):
    """A mono Ogg Opus stream of `seconds` of silence."""
    head = b"OpusHead" + bytes([1, 1]) + struct.pack("<HIhB", PRE_SKIP, RATE, 0, 0)
    tags = b"OpusTags" + struct.pack("<I", 4) + b"fake" + struct.pack("<I", 0)
    out = page(0x02, 0, 0, [head]) + page(0x00, 0, 1, [tags])
    left, granule, sequence = int(seconds * RATE / SAMPLES_PER_PACKET), PRE_SKIP, 2
    while left:
        count = min(left, 255)
        left -= count
        granule += count * SAMPLES_PER_PACKET
        out += page(0x04 if left == 0 else 0x00, granule, sequence, [PACKET] * count)
        sequence += 1
    return out


def duration_of(video_id):
    for album in json.loads(CATALOGUE.read_text())["albums"]:
        for track in album["tracks"]:
            if track["videoId"] == video_id:
                return track["duration_seconds"]
    raise DownloadError(f"ERROR: [youtube] {video_id}: Video unavailable")


class DownloadError(Exception):
    """As yt_dlp.utils.DownloadError."""


class YoutubeDL:
    def __init__(self, params):
        self.params = params

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        return False

    def extract_info(self, url, download=True):
        video_id = url.rsplit("=", 1)[-1]
        info = {"id": video_id, "format_id": "251", "acodec": "opus", "abr": 136.4, "asr": RATE}
        if self.params.get("test"):
            return info
        seconds = duration_of(video_id)
        data = silence(seconds)
        path = os.path.join(self.params["paths"]["home"], f"{video_id}.opus")
        for hook in self.params.get("progress_hooks", []):
            hook({"status": "downloading", "downloaded_bytes": 0, "total_bytes": len(data)})
        Path(path).write_bytes(data)
        for hook in self.params.get("progress_hooks", []):
            hook({"status": "finished", "downloaded_bytes": len(data), "total_bytes": len(data)})
        return dict(info, duration=seconds, ext="opus", requested_downloads=[{"filepath": path}])
