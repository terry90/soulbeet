"""Stands in for ytmusicapi in the e2e stack: answers from the catalogue fixtures/generate.ts
writes next to these packages, from fixtures/ytdlp-dataset.ts. A search names an album or a
song by "{artist} {title}"; a query the catalogue lists as rate limited fails as ytmusicapi does
when YouTube Music answers 429."""

import json
from pathlib import Path

CATALOGUE = Path(__file__).resolve().parent.parent / "catalogue.json"


class YTMusicServerError(Exception):
    """As ytmusicapi.exceptions.YTMusicServerError."""


def catalogue():
    return json.loads(CATALOGUE.read_text())


def artists(album):
    return [{"name": album["artist"], "id": "UCe2e"}]


class YTMusic:
    def search(self, query, filter=None, limit=20):
        shelf = catalogue()
        if query in shelf["rate_limited_queries"]:
            raise YTMusicServerError("Server returned HTTP 429: Too Many Requests.\n")
        wanted = query.casefold()
        if filter == "albums":
            return [
                {
                    "resultType": "album",
                    "browseId": album["browseId"],
                    "title": album["title"],
                    "artists": artists(album),
                    "year": album["year"],
                    "isExplicit": False,
                }
                for album in shelf["albums"]
                if f"{album['artist']} {album['title']}".casefold() == wanted
            ]
        return [
            {
                "resultType": "song",
                "videoId": track["videoId"],
                "title": track["title"],
                "artists": artists(album),
                "album": {"name": album["title"], "id": album["browseId"]},
                "duration_seconds": track["duration_seconds"],
                "videoType": "MUSIC_VIDEO_TYPE_ATV",
                "isAvailable": True,
                "isExplicit": False,
            }
            for album in shelf["albums"]
            for track in album["tracks"]
            if f"{album['artist']} {track['title']}".casefold() == wanted
        ]

    def get_album(self, browseId):
        album = next(a for a in catalogue()["albums"] if a["browseId"] == browseId)
        return {
            "title": album["title"],
            "artists": artists(album),
            "year": album["year"],
            "tracks": [
                {
                    "videoId": track["videoId"],
                    "title": track["title"],
                    "artists": artists(album),
                    "trackNumber": track["trackNumber"],
                    "duration_seconds": track["duration_seconds"],
                    "isAvailable": True,
                    "videoType": "MUSIC_VIDEO_TYPE_ATV",
                    "isExplicit": False,
                }
                for track in album["tracks"]
            ],
        }
